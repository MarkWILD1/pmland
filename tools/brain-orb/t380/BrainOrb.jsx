function dotScale(size) {
  return (size / 300) ** 0.6 * (size / TARGET) ** 0.4;
}

function makeProj(yaw, tilt, cx, cy, scale) {
  const st = Math.sin(tilt);
  const ct = Math.cos(tilt);
  const sy = Math.sin(yaw);
  const cyw = Math.cos(yaw);
  return (x, y, z) => {
    const x1 = x * cyw + z * sy;
    const z1 = -x * sy + z * cyw;
    const y1 = y * ct - z1 * st;
    const z2 = y * st + z1 * ct;
    return [cx + x1 * scale, cy - y1 * scale, z2];
  };
}

function ancestorDark(el) {
  let node = el;
  while (node) {
    const attr = node.getAttribute?.('data-theme');
    if (attr === 'dark') return true;
    if (attr === 'light') return false;
    if (node.classList?.contains('dark')) return true;
    if (node.classList?.contains('light')) return false;
    node = node.parentElement;
  }
  return null;
}

export function BrainOrb({
  size = TARGET,
  theme = 'auto',
  speed = 1,
  paused = false,
  label = "brain strokes",
  className,
}) {
  const hostRef = useRef(null);
  const canvasRef = useRef(null);
  const clock = useRef(0);
  const [dark, setDark] = useState(true);

  useEffect(() => {
    if (theme === 'dark') {
      setDark(true);
      return undefined;
    }
    if (theme === 'light') {
      setDark(false);
      return undefined;
    }

    const resolve = () => {
      const fromTree = ancestorDark(hostRef.current);
      const system =
        typeof matchMedia === 'undefined' || matchMedia('(prefers-color-scheme: dark)').matches;
      setDark(fromTree ?? system);
    };
    resolve();

    const mq = typeof matchMedia !== 'undefined' ? matchMedia('(prefers-color-scheme: dark)') : null;
    mq?.addEventListener('change', resolve);

    let observer = null;
    if (typeof MutationObserver !== 'undefined') {
      observer = new MutationObserver(resolve);
      observer.observe(document.documentElement, {
        attributes: true,
        attributeFilter: ['class', 'data-theme'],
        subtree: true,
      });
    }

    return () => {
      mq?.removeEventListener('change', resolve);
      observer?.disconnect();
    };
  }, [theme]);

  useEffect(() => {
    const canvas = canvasRef.current;
    const host = hostRef.current;
    if (!canvas || !host) return undefined;

    const ctx = canvas.getContext('2d');
    if (!ctx) return undefined;

    const dots = POINTS.map(() => ({ x: 0, y: 0, z: 0, r: 1, white: 0.5, a: 1 }));
    const reducedQuery = window.matchMedia('(prefers-reduced-motion: reduce)');
    let reduced = reducedQuery.matches;
    let visible = false;
    let pageVisible = document.visibilityState !== 'hidden';
    let raf = 0;
    let running = false;

    const resize = () => {
      const dpr = Math.min(window.devicePixelRatio || 1, 2);
      canvas.width = Math.round(size * dpr);
      canvas.height = Math.round(size * dpr);
      canvas.style.width = `${size}px`;
      canvas.style.height = `${size}px`;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    };

    const paint = (seconds) => {
      const t = reduced || paused ? 0 : seconds * speed;
      if (!reduced && !paused) clock.current = seconds;
      const yaw = YAW_AMP * Math.sin(t * YAW_SPEED);
      const tilt = TILT_AMP * Math.sin(t * TILT_SPEED);
      const project = makeProj(yaw, tilt, size / 2, size / 2, (size / 2) * SPHERE);
      const scale = dotScale(size);

      for (let i = 0; i < POINTS.length; i += 1) {
        const point = POINTS[i];
        const [x, y, z] = project(point[0], point[1], point[2]);
        const depth = (z + 1) / 2;
        const contour = point[4] === 0;
        const tone = point[3];
        let white = INK_FAR - INK_SPAN * depth - (contour ? CONTOUR_INK : 0);
        white += (1 - tone) * TONE_LIFT;
        if (white < 0) white = 0;
        else if (white > 1) white = 1;
        const dot = dots[i];
        dot.x = x;
        dot.y = y;
        dot.z = z;
        dot.r = Math.max(R_MIN, (R_BASE + R_DEPTH * depth) * (contour ? CONTOUR_BOOST : 1) * scale);
        dot.white = white;
        dot.a = z < -0.15 ? Math.max(0, (z + 1) / 0.85) : 1;
      }

      const order = dots.slice().sort((a, b) => a.z - b.z);
      ctx.clearRect(0, 0, size, size);
      for (let i = 0; i < order.length; i += 1) {
        const dot = order[i];
        if (dot.a < 0.02) continue;
        const g = Math.round((dark ? 1 - dot.white : dot.white) * 255);
        ctx.fillStyle = `rgba(${g},${g},${g},${dot.a})`;
        ctx.beginPath();
        ctx.arc(dot.x, dot.y, dot.r, 0, Math.PI * 2);
        ctx.fill();
      }
    };

    const frame = (now) => {
      paint(now / 1000);
      if (running) raf = requestAnimationFrame(frame);
    };

    const start = () => {
      if (running || reduced || paused || !visible || !pageVisible) return;
      running = true;
      raf = requestAnimationFrame(frame);
    };

    const stop = () => {
      running = false;
      cancelAnimationFrame(raf);
    };

    resize();
    paint(clock.current);

    const onReduce = () => {
      reduced = reducedQuery.matches;
      if (reduced) {
        stop();
        paint(0);
      } else {
        start();
      }
    };
    reducedQuery.addEventListener('change', onReduce);

    let observer = null;
    if (typeof IntersectionObserver !== 'undefined') {
      observer = new IntersectionObserver(
        ([entry]) => {
          visible = entry.isIntersecting;
          if (visible && pageVisible) start();
          else stop();
        },
        { threshold: 0.2 }
      );
      observer.observe(canvas);
    } else {
      visible = true;
      start();
    }

    const onVis = () => {
      pageVisible = document.visibilityState !== 'hidden';
      if (pageVisible && visible) start();
      else stop();
    };
    document.addEventListener('visibilitychange', onVis);

    return () => {
      stop();
      observer?.disconnect();
      reducedQuery.removeEventListener('change', onReduce);
      document.removeEventListener('visibilitychange', onVis);
    };
  }, [dark, paused, size, speed]);

  return (
    <div
      ref={hostRef}
      className={className}
      style={{ display: 'grid', placeItems: 'center', lineHeight: 0 }}
    >
      <canvas
        ref={canvasRef}
        role="img"
        aria-label={label}
        style={{ display: 'block', width: size, height: size }}
      />
    </div>
  );
}
