function dotScale(next) {
  return (next / 300) ** 0.6 * (next / TARGET) ** 0.4;
}

function makeProj(yaw, tilt, cx, cy, scale) {
  const st = Math.sin(tilt);
  const ct = Math.cos(tilt);
  const sy = Math.sin(yaw);
  const cyw = Math.cos(yaw);
  return (x, y, z) => {
    const x1 = x * cyw + z * sy;
    const z1 = -x * sy + z * cyw;
    const y1 = y * ct - z1 * st;
    const z2 = y * st + z1 * ct;
    return [cx + x1 * scale, cy - y1 * scale, z2];
  };
}

function frac(value) {
  return value - Math.floor(value);
}

function smooth(value) {
  const t = value < 0 ? 0 : value > 1 ? 1 : value;
  return t * t * (3 - 2 * t);
}

function buildField(points) {
  const count = points.length;
  let minY = Infinity;
  let maxY = -Infinity;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < count; i += 1) {
    const y = points[i][1];
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
    cx += points[i][0];
    cy += y;
  }
  cx /= count;
  cy /= count;
  const radius = (maxY - minY) / 2;
  const golden = Math.PI * (3 - Math.sqrt(5));
  const sphere = new Array(count);
  for (let i = 0; i < count; i += 1) {
    const y = 1 - (2 * (i + 0.5)) / count;
    const ring = Math.sqrt(Math.max(0, 1 - y * y));
    const angle = i * golden;
    sphere[i] = {
      x: cx + ring * Math.cos(angle) * radius,
      y: cy + y * radius,
      z: ring * Math.sin(angle) * radius,
    };
  }

  const bookOrder = new Array(count);
  const sphereOrder = new Array(count);
  for (let i = 0; i < count; i += 1) {
    bookOrder[i] = i;
    sphereOrder[i] = i;
  }
  bookOrder.sort(
    (a, b) => Math.atan2(points[a][1] - cy, points[a][0] - cx) - Math.atan2(points[b][1] - cy, points[b][0] - cx) || a - b
  );
  sphereOrder.sort(
    (a, b) => Math.atan2(sphere[a].y - cy, sphere[a].x - cx) - Math.atan2(sphere[b].y - cy, sphere[b].x - cx) || a - b
  );

  const routes = new Array(count);
  for (let k = 0; k < count; k += 1) {
    const index = bookOrder[k];
    const target = sphere[sphereOrder[k]];
    routes[index] = {
      x: target.x,
      y: target.y,
      z: target.z,
      delay: frac(Math.sin(index * 127.1 + 311.7) * 43758.5453),
      bow: (frac(Math.sin(index * 269.5 + 183.3) * 43758.5453) - 0.5) * radius * 0.28,
      zBow: (frac(Math.sin(index * 419.2 + 71.9) * 43758.5453) - 0.5) * radius * 0.16,
    };
  }
  return { routes, cx };
}

function staged(u, start, end, delay) {
  const span = end - start;
  const stagger = span * 0.42;
  const t0 = start + delay * stagger;
  const t1 = t0 + (span - stagger);
  return smooth((u - t0) / (t1 - t0));
}

function blendAt(u, delay) {
  if (u < OUT_A || u >= BACK_B) return 0;
  if (u < OUT_B) return staged(u, OUT_A, OUT_B, delay);
  if (u < BACK_A) return 1;
  return 1 - staged(u, BACK_A, BACK_B, delay);
}

function yawAt(u) {
  const peak = (BACK_A - OUT_B) * CYCLE * 0.55;
  if (u < OUT_B || u >= BACK_B) return 0;
  if (u < BACK_A) return ((u - OUT_B) / (BACK_A - OUT_B)) * peak;
  return peak * (1 - smooth((u - BACK_A) / (BACK_B - BACK_A)));
}

function placePoint(point, route, progress, yaw, cx) {
  const c = Math.cos(yaw);
  const s = Math.sin(yaw);
  const localX = route.x - cx;
  const tx = cx + localX * c + route.z * s;
  const tz = -localX * s + route.z * c;
  const dx = tx - point[0];
  const dy = route.y - point[1];
  const len = Math.hypot(dx, dy) || 1;
  const lift = Math.sin(progress * Math.PI);
  return [
    point[0] + dx * progress + (-dy / len) * lift * route.bow,
    point[1] + dy * progress + (dx / len) * lift * route.bow,
    point[2] + (tz - point[2]) * progress + lift * route.zBow,
  ];
}

const FIELD = buildField(POINTS);
const ICON_MAX = 48;
const BONE = [246, 241, 233];
const SHADOW = [92, 78, 68];
const PAPER = [43, 34, 28];
const PAPER_SOFT = [133, 119, 108];

function iconSample(size) {
  if (size > ICON_MAX) return null;
  const cssPerModel = (size / 2) * SPHERE;
  const gap = 0.82;
  const minDist = gap / cssPerModel;
  const min2 = minDist * minDist;
  const bins = new Map();
  const indices = [];
  for (let i = 0; i < POINTS.length; i += 1) {
    if (POINTS[i][4] !== 0) continue;
    const point = POINTS[i];
    const gx = Math.floor(point[0] / minDist);
    const gy = Math.floor(point[1] / minDist);
    let near = false;
    for (let oy = -1; oy <= 1 && !near; oy += 1) {
      for (let ox = -1; ox <= 1; ox += 1) {
        const bucket = bins.get(gx + ox + ',' + gy + oy);
        if (!bucket) continue;
        for (let b = 0; b < bucket.length; b += 1) {
          const other = POINTS[bucket[b]];
          const dx = point[0] - other[0];
          const dy = point[1] - other[1];
          if (dx * dx + dy * dy < min2) {
            near = true;
            break;
          }
        }
      }
    }
    if (near) continue;
    indices.push(i);
    const key = gx + ',' + gy;
    const bucket = bins.get(key);
    if (bucket) bucket.push(i);
    else bins.set(key, [i]);
  }
  return { indices, radius: 0.34 };
}

function inkColor(light, alpha, onDark) {
  const t = light < 0 ? 0 : light > 1 ? 1 : light;
  const from = onDark ? SHADOW : PAPER;
  const to = onDark ? BONE : PAPER_SOFT;
  const r = Math.round(from[0] + (to[0] - from[0]) * t);
  const g = Math.round(from[1] + (to[1] - from[1]) * t);
  const b = Math.round(from[2] + (to[2] - from[2]) * t);
  return 'rgba(' + r + ',' + g + ',' + b + ',' + alpha + ')';
}

export function mountLogoMarkOrb(host, options = {}) {
  if (!host) return;
  const sizeOf = typeof options.size === 'function' ? options.size : () => Number(options.size) || TARGET;
  const speed = options.speed ?? 1;
  const onDark = () => (typeof options.darkInk === 'function' ? options.darkInk() !== false : options.darkInk !== false);
  const canvas = document.createElement('canvas');
  canvas.setAttribute('role', 'img');
  canvas.setAttribute('aria-label', options.label || 'Plan Maestro');
  host.appendChild(canvas);
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  let size = sizeOf();
  let icon = iconSample(size);
  let drawList = icon ? icon.indices : null;
  let dots = (drawList ?? POINTS).map(() => ({ x: 0, y: 0, z: 0, r: 1, white: 0.5, a: 1 }));
  const reducedQuery = window.matchMedia('(prefers-reduced-motion: reduce)');
  let reduced = reducedQuery.matches;
  let visible = false;
  let pageVisible = document.visibilityState !== 'hidden';
  let raf = 0;
  let running = false;

  const resize = () => {
    const next = sizeOf();
    if (next !== size) {
      size = next;
      icon = iconSample(size);
      drawList = icon ? icon.indices : null;
      dots = (drawList ?? POINTS).map(() => ({ x: 0, y: 0, z: 0, r: 1, white: 0.5, a: 1 }));
    }
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = Math.round(size * dpr);
    canvas.height = Math.round(size * dpr);
    canvas.style.width = size + 'px';
    canvas.style.height = size + 'px';
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  };

  const paint = (seconds) => {
    const t = reduced ? 0 : seconds * speed;
    const u = t > 0 ? (t % CYCLE) / CYCLE : 0;
    const yaw = yawAt(u);
    const project = makeProj(0, 0, size / 2, size / 2, (size / 2) * SPHERE);
    const scale = dotScale(size);
    const count = drawList ? drawList.length : POINTS.length;
    for (let n = 0; n < count; n += 1) {
      const i = drawList ? drawList[n] : n;
      const point = POINTS[i];
      const route = FIELD.routes[i];
      const progress = blendAt(u, route.delay);
      const placed = placePoint(point, route, progress, yaw, FIELD.cx);
      const projected = project(placed[0], placed[1], placed[2]);
      const x = projected[0];
      const y = projected[1];
      const z = projected[2];
      const depth = (z + 1) / 2;
      const contour = point[4] === 0;
      const tone = point[3];
      let white = INK_FAR - INK_SPAN * depth - (contour ? CONTOUR_INK : 0);
      white += (1 - tone) * TONE_LIFT;
      if (white < 0) white = 0;
      else if (white > 1) white = 1;
      const dot = dots[n];
      dot.x = x;
      dot.y = y;
      dot.z = z;
      dot.r = icon
        ? icon.radius
        : Math.max(R_MIN, (R_BASE + R_DEPTH * depth) * (contour ? CONTOUR_BOOST : 1) * scale);
      dot.white = icon ? 0.12 : white;
      dot.a = icon ? 0.95 : z < -0.15 ? Math.max(0, (z + 1) / 0.85) : 1;
    }
    const order = dots.slice(0, count).sort((a, b) => a.z - b.z);
    ctx.clearRect(0, 0, size, size);
    for (let i = 0; i < order.length; i += 1) {
      const dot = order[i];
      if (dot.a < 0.02) continue;
      const darkSurface = onDark();
      ctx.fillStyle = inkColor(darkSurface ? 1 - dot.white : dot.white, dot.a, darkSurface);
      ctx.beginPath();
      ctx.arc(dot.x, dot.y, dot.r, 0, Math.PI * 2);
      ctx.fill();
    }
  };

  const frame = (now) => {
    paint(now / 1000);
    if (running) raf = requestAnimationFrame(frame);
  };

  const start = () => {
    if (running || reduced || !visible || !pageVisible) return;
    running = true;
    raf = requestAnimationFrame(frame);
  };

  const stop = () => {
    running = false;
    cancelAnimationFrame(raf);
  };

  resize();
  paint(0);

  reducedQuery.addEventListener('change', () => {
    reduced = reducedQuery.matches;
    if (reduced) {
      stop();
      paint(0);
    } else {
      start();
    }
  });

  if (typeof IntersectionObserver !== 'undefined') {
    const observer = new IntersectionObserver(
      ([entry]) => {
        visible = Boolean(entry && entry.isIntersecting);
        if (visible) start();
        else stop();
      },
      { threshold: 0.15 }
    );
    observer.observe(canvas);
  } else {
    visible = true;
    start();
  }

  document.addEventListener('visibilitychange', () => {
    pageVisible = document.visibilityState !== 'hidden';
    if (pageVisible) start();
    else stop();
  });

  let resizeTimer = 0;
  window.addEventListener('resize', () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => {
      resize();
      if (!running) paint(reduced ? 0 : performance.now() / 1000);
    }, 150);
  });

  const preloader = host.closest('#preloader');
  if (preloader && typeof MutationObserver !== 'undefined') {
    const mo = new MutationObserver(() => {
      const hidden = preloader.style.display === 'none' || preloader.style.opacity === '0';
      if (hidden) {
        stop();
        mo.disconnect();
      }
    });
    mo.observe(preloader, { attributes: true, attributeFilter: ['style', 'class'] });
  }
}
